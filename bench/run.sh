# Globals (initialised so `set -u` is happy even when a section is skipped).
E_START=""; E_EMPTY=""; E_WORDS=""
MOON_START=""; MOON_EMPTY=""; MOON_ONE=""; MOON_N=""; MOON_BIG=""
MREL_START=""; MREL_EMPTY=""; MREL_ONE=""; MREL_N=""; MOONREL_BIG=""
HAVE_REAL=0
AFF=""; DIC=""; ENTRIES=""
N_ENTRIES="0"; N_ENTRIES_DECLARED="0"
ONLY_FLAG=""; RULE_LINES="?"; RULE_BLOCKS="?"

engine_start() { # <engine> <reps>
  local engine="$1" reps="$2"
  case "$engine" in
    native)   E_START="$(TIMED_ALLOWED_RC=2 timed "$reps" "$NATIVE")" ;;
    moon)     E_START="$(TIMED_ALLOWED_RC=2 timed "$reps" moon run cmd/main)" ;;
    moonrel)  E_START="$(TIMED_ALLOWED_RC=2 timed "$reps" moon run --release cmd/main)" ;;
    hunspell) E_START="$(timed "$reps" hunspell -v)" ;;
  esac
}

engine_empty() { # <engine> <aff> <dic> <reps>
  local engine="$1" aff="$2" dic="$3" reps="$4"
  case "$engine" in
    native)   E_EMPTY="$(timed "$reps" "$NATIVE" check --aff "$aff" --dic "$dic" --words "$EMPTY_FILE")" ;;
    moon)     E_EMPTY="$(timed "$reps" moon run cmd/main -- check --aff "$aff" --dic "$dic" --words "$EMPTY_FILE")" ;;
    moonrel)  E_EMPTY="$(timed "$reps" moon run --release cmd/main -- check --aff "$aff" --dic "$dic" --words "$EMPTY_FILE")" ;;
    hunspell) E_EMPTY="$(timed "$reps" hunspell -d "$(hun_d "$dic")" -l "$EMPTY_FILE")" ;;
  esac
}

engine_words() { # <engine> <aff> <dic> <wordlist> <reps>
  local engine="$1" aff="$2" dic="$3" words="$4" reps="$5"
  case "$engine" in
    native)   E_WORDS="$(timed "$reps" "$NATIVE" check --aff "$aff" --dic "$dic" --words "$words")" ;;
    moon)     E_WORDS="$(timed "$reps" moon run cmd/main -- check --aff "$aff" --dic "$dic" --words "$words")" ;;
    moonrel)  E_WORDS="$(timed "$reps" moon run --release cmd/main -- check --aff "$aff" --dic "$dic" --words "$words")" ;;
    hunspell) E_WORDS="$(timed "$reps" hunspell -d "$(hun_d "$dic")" -l "$words")" ;;
  esac
}

