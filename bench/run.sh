  mkdir -p "$BENCH_TMP" || { echo "ERROR: cannot create BENCH_TMP=$BENCH_TMP" >&2; exit 1; }
  TMP="$(mktemp -d "$BENCH_TMP/spell-bench.XXXXXX")"
  CLEANUP=1
else
  TMP="$(mktemp -d)"
  CLEANUP=1
fi
if [ "$KEEP_TEMP" = "1" ]; then CLEANUP=0; fi
cleanup() { [ "$CLEANUP" = "1" ] && rm -rf "$TMP"; }
