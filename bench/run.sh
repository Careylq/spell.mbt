#!/usr/bin/env bash
#
# bench/run.sh — reproducible end-to-end performance benchmark for spell.mbt.
#
# One command produces every number in the `## Performance` section of README.mbt.md
# and every table in bench/README.md:
#
#   bash bench/run.sh
#
# What it measures
# ----------------
#   [1] The dictionary source (fetched at run time, NEVER vendored).
#   [2] The documented `moon run cmd/main -- check ...` path on the real en_US
#       dictionary: process start / dictionary load / per-word checking, separated
#       by timing three points (no-arg, empty word list, N words) and taking medians.
#   [3] Head-to-head against the system `hunspell` binary when one is installed.
#       This is BINARY vs BINARY: our `moon build --target native --release`
#       executable against the native hunspell, same `.aff`/`.dic`, same word list.
#   [4] A scaling curve on SYNTHETIC `.aff`/`.dic` pairs (1k / 10k / 50k / 200k
#       entries, fixed affix shape) generated by bench/gen_dict.sh.
#   [5] Release artifact sizes (wasm / wasm-gc / js / native).
#
# Honesty rules this script follows
# ---------------------------------
#   * Every number is measured here; nothing is hard-coded or estimated.
#   * Times are wall-clock medians over several repetitions (reps configurable).
#   * Nothing is fetched into the repository; the dictionary lives in a temp dir.
#   * If the network is unavailable the real-dictionary sections are SKIPPED with a
#     clear message and the synthetic + artifact sections still run. The script
#     still exits 0, because "no network" is not a benchmark failure.
#   * These are machine-specific end-to-end numbers. See bench/README.md.
#
# Environment overrides
# ---------------------
#   BENCH_REPS_SMALL=n     repetitions for start / load measurements   (default 9)
#   BENCH_REPS_BIG=n       repetitions for throughput measurements      (default 5)
#   BENCH_REPS_HUGE=n      repetitions for >=100k-word measurements     (default 3)
#   BENCH_SIZES="..."      synthetic dictionary sizes      (default "1000 10000 50000 200000")
#   BENCH_MAIN_WORDS=path  large word list              (default /usr/share/dict/words)
#   BENCH_FALLBACK_WORDS=n size of the generated fallback list          (default 200000)
#   BENCH_MEASURE_WORDS=n  words checked per synthetic size (see section 4) (default 100000)
#   BENCH_SKIP_REAL=1      skip the fetched real dictionary
#   BENCH_SKIP_HUNSPELL=1  skip the head-to-head
#   BENCH_KEEP_TEMP=1      keep the temp directory and print its path
#   BENCH_TMP=dir          scratch parent dir (a fresh subdir is created there and removed)
#
# Exit status: 0 when a report was produced, 1 on a real failure (the build or the
# CLI contract is broken).

set -uo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$REPO_ROOT"
export PATH="$HOME/.moon/bin:$PATH"

REPS_SMALL="${BENCH_REPS_SMALL:-9}"
REPS_BIG="${BENCH_REPS_BIG:-5}"
REPS_HUGE="${BENCH_REPS_HUGE:-3}"
SIZES="${BENCH_SIZES:-1000 10000 50000 200000}"
MAIN_WORDS="${BENCH_MAIN_WORDS:-/usr/share/dict/words}"
FALLBACK_WORDS="${BENCH_FALLBACK_WORDS:-200000}"
MEASURE_WORDS="${BENCH_MEASURE_WORDS:-100000}"
KEEP_TEMP="${BENCH_KEEP_TEMP:-0}"
SKIP_REAL="${BENCH_SKIP_REAL:-0}"
SKIP_HUNSPELL="${BENCH_SKIP_HUNSPELL:-0}"
HUGE_THRESHOLD=100000

DICT_AFF_URL="https://cdn.jsdelivr.net/gh/LibreOffice/dictionaries@master/en/en_US.aff"
DICT_DIC_URL="https://cdn.jsdelivr.net/gh/LibreOffice/dictionaries@master/en/en_US.dic"
DICT_RDM_URL="https://cdn.jsdelivr.net/gh/LibreOffice/dictionaries@master/en/README_en_US.txt"

# ------------------------------------------------------------------ small helpers

TIMEFORMAT='%6R'
TAB="$(printf '\t')"

hr() { printf -- '--------------------------------------------------------------------------------\n'; }
section() { echo; hr; echo "== $1"; hr; }
have() { command -v "$1" >/dev/null 2>&1; }

median() {
  sort -n | awk '{a[NR]=$1} END{
    if (NR == 0) { print ""; exit }
    if (NR % 2) printf "%.4f\n", a[(NR + 1) / 2]
    else printf "%.4f\n", (a[NR / 2] + a[NR / 2 + 1]) / 2
  }'
}

# timed <reps> <cmd...>  -> median wall-clock seconds on stdout (4 dp).
# A non-zero exit is a hard error unless TIMED_ALLOWED_RC names that exact code
# (the no-argument run prints usage and exits 2 by design).
timed() {
  local reps="$1"; shift
  local allowed="${TIMED_ALLOWED_RC:-0}"
  local i t rc acc=""
  for ((i = 0; i < reps; i++)); do
    t=$( { time "$@" >/dev/null 2>&1; } 2>&1 ); rc=$?
    if [ "$rc" -ne 0 ] && [ "$rc" -ne "$allowed" ]; then
      echo "ERROR: command failed (exit $rc): $*" >&2
      return 1
    fi
    acc="$acc$t"$'\n'
  done
  printf '%s' "$acc" | median
}

# Float formatting (awk, so this works with the system bash 3.2 on macOS).
f_s()     { awk -v x="${1:-0}" 'BEGIN{printf "%.4f", x + 0}'; }
f_ms()    { awk -v x="${1:-0}" 'BEGIN{printf "%.2f", (x + 0) * 1000}'; }
f_us()    { awk -v t="${1:-0}" -v n="${2:-0}" 'BEGIN{ if (n <= 0) printf "n/a"; else printf "%.2f", 1e6 * t / n }'; }
f_wps()   { awk -v n="${1:-0}" -v t="${2:-0}" 'BEGIN{ if (t <= 0) printf "n/a"; else printf "%.0f", n / t }'; }
f_ratio() { awk -v a="${1:-0}" -v b="${2:-0}" 'BEGIN{ if (b <= 0) printf "n/a"; else printf "%.2fx", a / b }'; }
f_pct()   { awk -v a="${1:-0}" -v b="${2:-0}" 'BEGIN{ if (b <= 0) printf "n/a"; else printf "%.1f%%", 100 * a / b }'; }
f_sub()   { awk -v a="${1:-0}" -v b="${2:-0}" 'BEGIN{printf "%.6f", a - b}'; }
f_gib()   { awk -v b="${1:-0}" 'BEGIN{ if (b <= 0) printf "?"; else printf "%.0f GiB", b / 1073741824}'; }

# Number of non-empty lines in a file.
word_count() { grep -c . "$1" 2>/dev/null | tr -d ' '; }

# The `hunspell -d` spelling of a dictionary whose files are <dir>/<base>.aff/.dic.
hun_d() { printf '%s/%s' "$(dirname "$1")" "$(basename "$1" .dic)"; }

# Verdicts for one word per line: 1 = accepted, 0 = rejected. Only the two
# engines that answer per word are supported here (hunspell lists misses only).
verdicts() { # <engine> <aff> <dic> <wordlist>
  local engine="$1" aff="$2" dic="$3" words="$4"
  case "$engine" in
    native) "$NATIVE" check --aff "$aff" --dic "$dic" --words "$words" 2>/dev/null ;;
    moon)   moon run cmd/main -- check --aff "$aff" --dic "$dic" --words "$words" 2>/dev/null ;;
  esac
}

