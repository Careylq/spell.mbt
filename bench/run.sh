build_target() { # <target>
  local target="$1" label="$2"
  if moon build --target "$target" --release >/dev/null 2>&1; then
    printf '  moon build --release --target %-8s ok (%s)\n' "$target" "$label"
  else
    printf '  moon build --release --target %-8s FAILED\n' "$target"
  fi
}
