section "5. release artifact size"
artifact() { # <label> <path>
  if [ -f "$2" ]; then
    printf '  %-9s %12s bytes   %s\n' "$1" "$(wc -c < "$2" | tr -d ' ')" "$2"
  else
    printf '  %-9s %12s         %s\n' "$1" "missing" "$2"
  fi
}
